static bool sly_get_pixel(uint8_t x, uint8_t y) {
    if (x >= SLY_SRC_WIDTH || y >= SLY_SRC_HEIGHT) {
        return false;
    }

    uint16_t index = ((uint16_t)y * SLY_ROW_BYTES) + (x >> 3);
    uint8_t byte = pgm_read_byte(&sly_bitmap[index]);
    uint8_t mask = 0x80 >> (x & 7);

    return (byte & mask) != 0;
}

static void oled_set_buffer_pixel(uint8_t *buffer, uint8_t x, uint8_t y, bool on) {
    if (x >= OLED_WIDTH || y >= OLED_HEIGHT) {
        return;
    }

    uint16_t index = x + (y / 8) * OLED_WIDTH;
    uint8_t mask = 1 << (y & 7);

    if (on) {
        buffer[index] |= mask;
    } else {
        buffer[index] &= ~mask;
    }
}

void render_sly_logo(void) {
    uint8_t buffer[OLED_BUF_SIZE];
    memset(buffer, 0, sizeof(buffer));

    const uint8_t offset_x = (OLED_WIDTH - SLY_DST_WIDTH) / 2;
    const uint8_t offset_y = (OLED_HEIGHT - SLY_DST_HEIGHT) / 2;

    for (uint8_t dy = 0; dy < SLY_DST_HEIGHT; dy++) {
        uint8_t sy = ((uint16_t)dy * SLY_SRC_HEIGHT) / SLY_DST_HEIGHT;

        for (uint8_t dx = 0; dx < SLY_DST_WIDTH; dx++) {
            uint8_t sx = ((uint16_t)dx * SLY_SRC_WIDTH) / SLY_DST_WIDTH;
            bool pixel = sly_get_pixel(sx, sy);

            /*
             * Rotate 180 degrees by flipping both axes.
             */
            uint8_t rx = offset_x + (SLY_DST_WIDTH - 1 - dx);
            uint8_t ry = offset_y + (SLY_DST_HEIGHT - 1 - dy);

            /*
             * Source image:
             *   1 = white background
             *   0 = dark logo
             *
             * Invert it so the logo is lit on the OLED.
             */
            oled_set_buffer_pixel(buffer, rx, ry, !pixel);
        }
    }

    oled_write_raw((const char *)buffer, sizeof(buffer));
}